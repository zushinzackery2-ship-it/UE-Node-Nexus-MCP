"""Inherited Blueprint templates contain isolated disabled event/parent pairs."""

from copy import deepcopy

import pytest

from ue_node_nexus_mcp.transcode.raw.blueprint import _visible_nodes


def pin(identity, name, direction, linked=None, category="exec"):
    return dict(guid=identity, name=name, dir=direction, linked=linked or [],
                type=dict(category=category), default="", autogenerated="")


def template():
    event = dict(guid="event", class_short="Event", enabled=False,
                 config=dict(function_name="ReceiveTick", function_owner="/Script/Engine.ActorComponent"),
                 pins=[pin("event-exec", "then", "out", ["parent-exec"]),
                       pin("event-delta", "DeltaSeconds", "out", ["parent-delta"], "real")])
    parent = dict(guid="parent", class_short="CallParentFunction", enabled=False,
                  config=dict(function_name="ReceiveTick", function_owner="/Game/Test/BP_Data.BP_Data_C"),
                  pins=[pin("parent-exec", "execute", "in", ["event-exec"]),
                        pin("parent-delta", "DeltaSeconds", "in", ["event-delta"], "real"),
                        pin("parent-then", "then", "out")])
    end = dict(guid="end", class_short="Event", enabled=True,
               config=dict(function_name="ReceiveEndPlay"), pins=[])
    return dict(nodes=[event, parent, end])


def test_disabled_template_parent_pair_is_not_an_authored_lifecycle():
    assert [node["guid"] for node in _visible_nodes(template())] == ["end"]


@pytest.mark.parametrize("change", ["event_enabled", "parent_enabled", "different_method", "consumer",
                                    "parent_output", "literal_override", "changed_property"])
def test_modified_or_active_lifecycle_is_kept(change):
    graph = deepcopy(template())
    event, parent, end = graph["nodes"]
    if change == "event_enabled":
        event["enabled"] = True
    elif change == "parent_enabled":
        parent["enabled"] = True
    elif change == "different_method":
        parent["config"]["function_name"] = "ReceiveBeginPlay"
    elif change == "consumer":
        event["pins"][1]["linked"].append("external")
        end["pins"].append(pin("external", "Value", "in", ["event-delta"], "real"))
    elif change == "parent_output":
        parent["pins"][2]["linked"].append("external")
        end["pins"].append(pin("external", "execute", "in", ["parent-then"]))
    elif change == "literal_override":
        parent["pins"].append(dict(pin("extra", "Extra", "in", category="real"), default="2"))
    else:
        parent["props"] = [dict(name="Custom", value="True", default="False")]
    assert [node["guid"] for node in _visible_nodes(graph)] == ["event", "parent", "end"]
