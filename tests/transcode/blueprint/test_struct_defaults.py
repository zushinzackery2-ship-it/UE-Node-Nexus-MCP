"""Preserve authored composite defaults whose native initialization is not all zero."""

from copy import deepcopy

import pytest

from ue_node_nexus_mcp.transcode.blueprint.types import is_zero_default, parse_type_text
from ue_node_nexus_mcp.transcode.collaboration.apply.transactions import actual_snapshot
from ue_node_nexus_mcp.transcode.collaboration.semantic.snapshot import capture, text_of
from ue_node_nexus_mcp.transcode.errors import SyncError
from ue_node_nexus_mcp.transcode.raw.blueprint import variable_decl
from ue_node_nexus_mcp.transcode.raw.nodes import pin_default_params
from tests.support.semantics import receipt_workspace, self_graph_raw


QUAT = 'Struct(/Script/CoreUObject.Quat)'
ZERO = '(X=0,Y=0,Z=0,W=0)'
IDENTITY = '(X=0,Y=0,Z=0,W=1)'


@pytest.mark.parametrize('kind,literal', (
    (QUAT, ZERO),
    ('Struct(/Script/CoreUObject.Quat4f)', ZERO),
    ('Struct(/Game/Custom/Settings.Settings)', '(Mode=0,Scale=0)'),
    ('Struct(/Script/CoreUObject.LinearColor)', '(R=0,G=0,B=0,A=0)')))
def test_composite_zero_is_not_assumed_to_equal_native_default(kind, literal):
    assert not is_zero_default(literal, kind)
    declaration = variable_decl(dict(name='Value', type=parse_type_text(kind), default=literal))
    assert declaration.default == literal


@pytest.mark.parametrize('kind,literal', (
    ('Struct(/Script/CoreUObject.Vector)', '(X=0,Y=0,Z=0)'),
    ('Struct(/Script/CoreUObject.Vector2D)', '(X=0,Y=0)'),
    ('Struct(/Script/CoreUObject.Rotator)', '(Pitch=0,Yaw=0,Roll=0)')))
def test_proven_zero_initialized_structs_keep_sparse_declarations(kind, literal):
    assert is_zero_default(literal, kind)
    assert not is_zero_default(literal.replace('=0', '=1', 1), kind)


@pytest.mark.parametrize('kind', ('array', 'set', 'map', 'Array<name>', 'Set<int>', 'Map<name,int>'))
def test_empty_container_default_keeps_legacy_and_typed_native_contract(kind):
    assert is_zero_default('()', kind)
    assert not is_zero_default('(0)', kind)


@pytest.mark.parametrize('literal', ('(X=0,Y=0,Z=0,W=0)', '(W=0,Z=0,Y=0,X=0)'))
def test_quaternion_zero_survives_semantic_capture_and_render(literal):
    snapshot = capture(
        'nexus: 1\nasset: /Game/BP_Test\nclass: Blueprint\nschema: key\n'
        '[variables]\nRotation : ' + QUAT + ' = ' + literal + ' {Transient}\n',
        None, 'author', 'blueprint')
    assert '= (W=0,X=0,Y=0,Z=0)' in text_of(snapshot)


@pytest.mark.parametrize('autogenerated', (None, '', IDENTITY))
def test_quaternion_zero_pin_is_preserved_without_matching_generated_default(autogenerated):
    pin = dict(name='Rotation', dir='in', type=parse_type_text(QUAT), default=ZERO)
    if autogenerated is not None:
        pin['autogenerated'] = autogenerated
    assert pin_default_params([pin], set()) == [('Rotation', ZERO)]


def test_reflected_pin_default_is_authoritative_for_any_struct():
    pin = dict(name='Rotation', dir='in', type=parse_type_text(QUAT), default=ZERO, autogenerated=ZERO)
    assert pin_default_params([pin], set()) == []


def test_actual_readback_matches_zero_quaternion_and_rejects_identity(tmp_path):
    raw = self_graph_raw()
    raw['blueprint'] = dict(graphs=[], variables=[dict(
        name='Rotation', guid='ROTATION', type=parse_type_text(QUAT), default=ZERO, flags=['Transient'])])
    candidate = capture(
        'nexus: 1\nasset: /Game/BP_Test\nclass: Blueprint\nschema: key\n'
        '[variables]\nRotation : ' + QUAT + ' = ' + ZERO + ' {Transient}\n',
        None, 'author', 'blueprint')
    workspace, commit, asset = receipt_workspace(tmp_path, candidate)
    record = dict(id='apply', candidate=commit, asset=asset,
                  request=dict(plan=[dict(op='bp_variable_add', name='Rotation')]),
                  receipt=dict(after=raw, response_data=dict(id_map=dict())))
    assert actual_snapshot(workspace, record)
    altered = deepcopy(record)
    altered['receipt']['after']['blueprint']['variables'][0]['default'] = IDENTITY
    with pytest.raises(SyncError) as error:
        actual_snapshot(workspace, altered)
    assert error.value.code == 'apply_result_mismatch'
