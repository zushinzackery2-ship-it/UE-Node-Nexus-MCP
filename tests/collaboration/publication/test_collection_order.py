"""A new collection declaration reaches UE before a same-batch consumer uses it."""

from pathlib import Path

from tests.collaboration.fake_bridge import ProtocolUe
from tests.transcode.fake_ue import SCHEMA_KEY
from tests.transcode.fixtures import prop
from ue_node_nexus_mcp.transcode.schema.catalog import publish
from ue_node_nexus_mcp.transcode.sync.service import run_sync

COLLECTION = "/Game/Z_Collection.Z_Collection"
MATERIAL = "/Game/Materials/M_Glass.M_Glass"
CLASS = "/Script/Engine.MaterialExpressionCollectionParameter"
BLUEPRINT = "/Game/A_Toon.A_Toon"
SETTER = "/Script/Engine.KismetMaterialLibrary.SetScalarParameterValue"
HOST = "/Script/BlueprintGraph.K2Node_CallMaterialParameterCollectionFunction"


class CollectionUe(ProtocolUe):
    def _apply_verb(self, raw, verb, ids, id_map):
        if raw["kind"] != "blueprint" or verb["op"] != "set_node_param":
            return super()._apply_verb(raw, verb, ids, id_map)
        assert verb["name"] == "ParameterName"
        # The real Blueprint compiler rejects an undeclared collection parameter.
        declaration = self.assets[COLLECTION]["props"][0]["value"]
        assert "ParameterName=" + verb["value"] in declaration
        node = next(row for row in raw["blueprint"]["graphs"][0]["nodes"] if row["guid"] == ids[verb["id"]])
        pin = next(row for row in node["pins"] if row["name"] == verb["name"])
        pin["default"] = verb["value"]


def setter_pin(name, category, default="", direction="in", subobject=""):
    return dict(guid="pin-" + name, name=name, dir=direction, default=default, autogenerated="",
                linked=[], hidden=False, type=dict(category=category, subobject=subobject, container="none", is_ref=False))


def test_collection_precedes_material_that_uses_new_parameter(tmp_path):
    ue = ProtocolUe()
    ue.assets[COLLECTION] = dict(raw_version=1, kind="asset", schema_key=SCHEMA_KEY, asset_path=COLLECTION,
                                class_short="MaterialParameterCollection", **{"class": "/Script/Engine.MaterialParameterCollection"},
                                props=[prop("ScalarParameters", "TArray<FCollectionScalarParameter>", "()", "()")])
    ue.assets[MATERIAL]["graph"]["nodes"].append(dict(guid="COLLECTION-CALL", name="Collection", class_short="CollectionParameter",
        x=-600, y=0, inputs=[], outputs=[""], props=[prop("Collection", "UMaterialParameterCollection*", COLLECTION, "None"),
        prop("ParameterName", "FName", "Old", "None")], **{"class": CLASS}))
    env = dict(UE_NEXUS_TRANSCODE_DIR=str(tmp_path / "mirror"))
    workspace = run_sync(ue, "checkout", options=dict(dry_run=False, agent_id="collection"), env=env)
    schema = tmp_path / "mirror/.nexus/schema" / SCHEMA_KEY
    publish(schema, SCHEMA_KEY, dict(asset={"MaterialParameterCollection": dict(path="/Script/Engine.MaterialParameterCollection", props=dict(
        ScalarParameters=dict(type="array", default="()")))}, material_expression={CLASS: dict(path=CLASS, inputs=[], outputs=[""], props=dict(
        Collection=dict(type="object", default="None"), ParameterName=dict(type="name", default="None")))}), incremental=True)
    provider = Path(workspace["file_paths"][COLLECTION])
    provider.write_text(provider.read_text(encoding="utf-8").replace("[asset]", "[asset]\nScalarParameters = ((ParameterName=Amount,DefaultValue=1))"), encoding="utf-8")
    consumer = Path(workspace["file_paths"][MATERIAL])
    consumer.write_text(consumer.read_text(encoding="utf-8").replace("ParameterName=Old", "ParameterName=Amount"), encoding="utf-8")
    options = dict(workspace_id=workspace["id"], dry_run=False)
    run_sync(ue, "commit", options=dict(options, all=True, message="collection declaration and consumer"), env=env)
    result = run_sync(ue, "push", [MATERIAL, COLLECTION], options, env=env)
    assert result["status"] == "published", result
    assert [payload["asset_path"] for payload in ue.applied] == [COLLECTION, MATERIAL]
    assert COLLECTION in [row["asset_path"] for row in ue.applied[1]["read_set"]]
    assert ue.assets[COLLECTION]["props"][0]["value"] == "((ParameterName=Amount,DefaultValue=1))"


def test_collection_precedes_blueprint_setter_using_new_parameter(tmp_path):
    ue = CollectionUe()
    ue.assets[COLLECTION] = dict(raw_version=1, kind="asset", schema_key=SCHEMA_KEY, asset_path=COLLECTION,
        class_short="MaterialParameterCollection", props=[prop("ScalarParameters", "array", "()", "()")],
        **{"class": "/Script/Engine.MaterialParameterCollection"})
    pins = [setter_pin("execute", "exec"), setter_pin("then", "exec", direction="out"),
            setter_pin("Collection", "object", COLLECTION, subobject="/Script/Engine.MaterialParameterCollection"),
            setter_pin("ParameterName", "name", "Old")]
    node = dict(guid="setter-guid", class_short="CallFunction", x=0, y=0, supported=True,
                config=dict(function_owner="/Script/Engine.KismetMaterialLibrary", function_name="SetScalarParameterValue"),
                props=[], pins=pins, **{"class": HOST})
    ue.assets[BLUEPRINT] = dict(raw_version=1, kind="blueprint", schema_key=SCHEMA_KEY, asset_path=BLUEPRINT,
        class_short="Blueprint", props=[], blueprint=dict(parent_class="/Script/Engine.Actor",
        graphs=[dict(name="EventGraph", kind="ubergraph", nodes=[node])]), **{"class": "/Script/Engine.Blueprint"})
    env = dict(UE_NEXUS_TRANSCODE_DIR=str(tmp_path / "mirror"))
    workspace = run_sync(ue, "checkout", [BLUEPRINT, COLLECTION], dict(dry_run=False), env=env)
    schema = tmp_path / "mirror/.nexus/schema" / SCHEMA_KEY
    record = dict(node_class=HOST, params=[dict(name=row["name"], dir=row["dir"], type=row["type"]) for row in pins])
    publish(schema, SCHEMA_KEY, dict(functions={SETTER: record}, k2node={HOST: dict(path=HOST, dynamic_pins=True)},
        asset={"MaterialParameterCollection": dict(path="/Script/Engine.MaterialParameterCollection",
                                                  props=dict(ScalarParameters=dict(type="array", default="()")))}), incremental=True)
    provider = Path(workspace["file_paths"][COLLECTION])
    provider.write_text(provider.read_text(encoding="utf-8").replace("[asset]", "[asset]\nScalarParameters = ((ParameterName=Amount,DefaultValue=1))"), encoding="utf-8")
    consumer = Path(workspace["file_paths"][BLUEPRINT])
    text = consumer.read_text(encoding="utf-8")
    assert "ParameterName=Old" in text
    consumer.write_text(text.replace("ParameterName=Old", "ParameterName=Amount"), encoding="utf-8")
    options = dict(workspace_id=workspace["id"], dry_run=False)
    run_sync(ue, "commit", options=dict(options, all=True, message="collection declaration and Blueprint setter"), env=env)
    result = run_sync(ue, "push", [BLUEPRINT, COLLECTION], options, env=env)
    assert result["status"] == "published", result
    assert [payload["asset_path"] for payload in ue.applied] == [COLLECTION, BLUEPRINT]
    assert COLLECTION in [row["asset_path"] for row in ue.applied[1]["read_set"]]
    assert next(row for row in ue.assets[BLUEPRINT]["blueprint"]["graphs"][0]["nodes"][0]["pins"]
                if row["name"] == "ParameterName")["default"] == "Amount"
