"""Authored IEEE zero signs must survive declarations, pins and strict readback."""

from copy import deepcopy

import pytest

from tests.support.semantics import receipt_workspace, self_graph_raw
from ue_node_nexus_mcp.transcode.blueprint.types import is_zero_default, parse_type_text
from ue_node_nexus_mcp.transcode.collaboration.apply.transactions import actual_snapshot
from ue_node_nexus_mcp.transcode.collaboration.semantic.snapshot import capture, text_of
from ue_node_nexus_mcp.transcode.errors import SyncError
from ue_node_nexus_mcp.transcode.raw.blueprint import variable_decl
from ue_node_nexus_mcp.transcode.raw.nodes import pin_default_params
from ue_node_nexus_mcp.transcode.text.semantic import normalize


@pytest.mark.parametrize('kind', ('float', 'double', 'real'))
@pytest.mark.parametrize('literal', ('-0', '-0.0', '-0.000000', '-0e30'))
def test_negative_zero_has_an_authored_floating_default(kind, literal):
    assert not is_zero_default(literal, kind)
    assert normalize(literal, kind) == '-0'


@pytest.mark.parametrize('kind', ('float', 'double', 'real', 'int', 'int64', 'byte'))
def test_positive_zero_remains_the_sparse_native_default(kind):
    assert is_zero_default('0', kind)
    assert normalize('0.000000', kind) == '0'


@pytest.mark.parametrize('kind', ('float', 'double'))
def test_negative_zero_raw_capture_and_actual_readback_preserve_sign(tmp_path, kind):
    raw = self_graph_raw()
    row = dict(name='Value', guid='VALUE', type=parse_type_text(kind), default='-0.000000', flags=['Transient'])
    raw['blueprint'] = dict(graphs=[], variables=[row])
    assert variable_decl(row).default == '-0.000000'
    candidate = capture(
        'nexus: 1\nasset: /Game/BP_Test\nclass: Blueprint\nschema: key\n'
        '[variables]\nValue : ' + kind + ' = -0.0 {Transient}\n', None, 'author', 'blueprint')
    assert ' = -0 ' in text_of(candidate)
    workspace, commit, asset = receipt_workspace(tmp_path, candidate)
    record = dict(id='apply', asset=asset, candidate=commit,
                  request=dict(plan=[dict(op='bp_variable_add', name='Value')]),
                  receipt=dict(after=raw, response_data=dict(id_map=dict())))
    assert actual_snapshot(workspace, record)
    wrong = deepcopy(record)
    wrong['receipt']['after']['blueprint']['variables'][0]['default'] = '0.000000'
    with pytest.raises(SyncError) as error:
        actual_snapshot(workspace, wrong)
    assert error.value.code == 'apply_result_mismatch'


@pytest.mark.parametrize('autogenerated', (None, '', '0', '0.000000', '-0', '-0.000000'))
def test_negative_zero_pin_omission_uses_the_reflected_sign(autogenerated):
    pin = dict(name='Value', dir='in', type=parse_type_text('float'), default='-0.0')
    if autogenerated is not None:
        pin['autogenerated'] = autogenerated
    expected = [] if autogenerated and autogenerated.startswith('-') else [('Value', '-0.0')]
    assert pin_default_params([pin], set()) == expected


@pytest.mark.parametrize('kind,literal', (
    ('Struct(/Script/CoreUObject.Vector)', '(X=-0.0,Y=0,Z=0)'),
    ('Struct(/Script/CoreUObject.Vector2D)', '(X=0,Y=-0.0)'),
    ('Struct(/Script/CoreUObject.Rotator)', '(Pitch=0,Yaw=-0.0,Roll=0)')))
def test_known_zero_struct_omission_cannot_erase_a_member_sign(kind, literal):
    assert not is_zero_default(literal, kind)
    assert '-0' in normalize(literal, kind)


@pytest.mark.parametrize('kind', ('int', 'int64', 'byte'))
def test_integer_zero_has_no_ieee_sign(kind):
    assert is_zero_default('-0', kind)
    assert normalize('-0', kind) == '0'
