"""Text values keep content through output, defaults and typed comparison."""

import pytest

from ue_node_nexus_mcp.transcode.raw.common import prop_entries
from ue_node_nexus_mcp.transcode.text.emitter import emit
from ue_node_nexus_mcp.transcode.text.model import Decl, Document, Header, Prop, Section
from ue_node_nexus_mcp.transcode.text.parser import parse
from ue_node_nexus_mcp.transcode.text.semantic import normalize
from ue_node_nexus_mcp.transcode.text.semantic import values_equal


@pytest.mark.parametrize("kind", ["FString", "FName", "FText", "string", "name", "text"])
@pytest.mark.parametrize("value", ["01.000", "1.000", "True", " 01.000 ", '(Key="01.000")'])
def test_typed_strings_keep_exact_content(kind, value):
    document = Document(Header(asset="/Game/Test/Data", cls="DataAsset"))
    document.sections = [Section("asset", entries=[Prop("Label", value, type_name=kind)]),
                         Section("variables", entries=[Decl("Label", kind, default=value)]),
                         Section("nodes", entries=[Decl("Node", "Expression", args=[("Label", value)],
                             props=[("Caption", value)], meta=dict(prop_types=dict(Label=kind), input_types=dict(Caption=kind)))])]
    output, diagnostics = parse(emit(document))
    assert not diagnostics.has_errors
    assert output.section("asset").props()[0].value == value
    assert output.section("variables").decls()[0].default == value
    node = output.section("nodes").decls()[0]
    assert node.args[0][1] == value
    assert node.props[0][1] == value
    assert normalize(value, kind) == value
    assert emit(output) == emit(document)


@pytest.mark.parametrize("kind", ["FString", "FName", "FText", "string", "name", "text"])
def test_numeric_string_default_is_not_omitted(kind):
    entries = prop_entries([dict(name="Label", type=kind, value="1.000", default="1")])
    assert len(entries) == 1
    assert not values_equal("1.000", "1", kind)
    assert not values_equal("True", "true", kind)
    assert values_equal("1.000", "1", "double")


def test_reflected_array_string_members_roundtrip(tmp_path):
    from ue_node_nexus_mcp.transcode.collaboration.semantic.snapshot import from_raw
    from ue_node_nexus_mcp.transcode.collaboration.history import History
    from ue_node_nexus_mcp.transcode.collaboration.store import Store
    from ue_node_nexus_mcp.transcode.collaboration.workspace import checkout

    contract = dict(kind="array", type="TArray<FOptions>", element=dict(kind="struct", type="FOptions",
        fields=dict(Label=dict(type="FString"), Name=dict(type="FName"), Caption=dict(type="FText"))))
    raw = dict(raw_version=1, asset_path="/Game/Test/Data.Data", class_short="DataAsset", kind="asset", schema_key="key",
        props=[dict(name="Options", type=contract["type"], value_schema=contract,
            value='((Label="01.000",Name="1.000",Caption=" True "))')])
    store = Store(tmp_path)
    history = History(store)
    snapshot = store.snapshot(from_raw(raw))
    root = history.create(history.tree(dict([(raw["asset_path"], snapshot)])), [], "strings")
    workspace = checkout(store, root)
    assert not workspace.status()["dirty"]
    file = workspace.root / workspace.state["files"][raw["asset_path"]]
    document, _ = parse(file.read_text(encoding="utf-8"))
    assert '"01.000"' in document.section("asset").props()[0].value
    assert '"1.000"' in document.section("asset").props()[0].value
    assert '" True "' in document.section("asset").props()[0].value


def test_blueprint_node_pin_and_property_type_namespaces():
    from ue_node_nexus_mcp.transcode.raw.nodes import node_decl
    from ue_node_nexus_mcp.transcode.text.emitter import emit_entry

    node = dict(class_short="CallFunction", props=[dict(name="Label", type="FString", value="1.000", default="1")],
        pins=[dict(name="Label", dir="in", type=dict(category="string"), default="01.000", autogenerated="")])
    declaration = node_decl("node", node)
    assert 'pin:Label="01.000"' in emit_entry(declaration)
    assert 'prop:Label="1.000"' in emit_entry(declaration)


def test_function_parameter_string_default_roundtrip():
    from ue_node_nexus_mcp.transcode.blueprint.signature import FunctionSignature, SignatureParam, parse_signature

    signature = FunctionSignature("Read", inputs=[SignatureParam("Label", "string", "01.000")])
    assert parse_signature(signature.text()).inputs[0].default == "01.000"


def test_diff_detects_string_content_change_in_all_typed_fields():
    from ue_node_nexus_mcp.transcode.diff.common import diff_brace_props, diff_params, diff_prop_section
    from ue_node_nexus_mcp.transcode.diff.plan import AssetPlan

    plan = AssetPlan("/Game/Data.Data", "asset")
    diff_prop_section(Section("asset", entries=[Prop("Label", "1")]),
        Section("asset", entries=[Prop("Label", "1.000", type_name="FString")]), plan, "set_asset_prop")
    before = Decl("node", "Node", args=[("Label", "1.000")], props=[("Caption", "1.000")],
        meta=dict(prop_types=dict(Label="FString", Caption="FString")))
    after = Decl("node", "Node", args=[("Label", "1")], props=[("Caption", "1")])
    diff_params(after, before, plan, "set_node_param")
    diff_brace_props(after, before, plan, "set_component_prop")
    assert len(plan.verbs) == 3

