"""Recognize the isolated disabled override/parent scaffold created by UE."""


def inherited_event_pair(event, pins):
    if event.get("class_short") != "Event" or event.get("enabled", True):
        return set()
    links = [str(identity) for pin in event.get("pins", []) for identity in pin.get("linked", [])]
    if not links or any(identity not in pins for identity in links):
        return set()
    parents = dict((str(pins[identity][0].get("guid", "")), pins[identity][0]) for identity in links)
    if len(parents) != 1:
        return set()
    parent = next(iter(parents.values()))
    if parent.get("class_short") != "CallParentFunction" or parent.get("enabled", True):
        return set()
    method = event.get("config", dict()).get("function_name")
    if not method or method != parent.get("config", dict()).get("function_name"):
        return set()
    identities = set(str(node.get("guid", "")) for node in (event, parent))
    kinds = set()
    for node in (event, parent):
        if any(row.get("value") != row.get("default") for row in node.get("props", [])):
            return set()
        for pin in node.get("pins", []):
            pin_kinds = pin_link_kinds(pin, node is event, pins, identities)
            if pin_kinds is None:
                return set()
            kinds.update(pin_kinds)
    return identities if "exec" in kinds else set()


def pin_link_kinds(pin, from_event, pins, identities):
    """Kinds of the pin's links; None when the pin holds an authored default or links outside the pair."""
    linked = pin.get("linked", [])
    if not linked and pin.get("dir") == "in" and pin.get("default", "") != pin.get("autogenerated", ""):
        return None
    kinds = []
    for identity in linked:
        other = pins.get(str(identity))
        if other is None or str(other[0].get("guid", "")) not in identities:
            return None
        kind = scaffold_link(pin, other[1], from_event)
        if kind is None:
            return None
        kinds.append(kind)
    return kinds


def scaffold_link(pin, other, from_event):
    """Kind ("exec" or "data") of a link shaped like the one UE's scaffold creates between the pair; None otherwise."""
    if str(pin.get("guid", "")) not in other.get("linked", []):
        return None
    source, target = (pin, other) if from_event else (other, pin)
    if source.get("dir") != "out" or target.get("dir") != "in":
        return None
    if source.get("type", dict()).get("category") == "exec":
        return "exec" if source.get("name") == "then" and target.get("name") == "execute" else None
    return "data" if source.get("name") == target.get("name") else None
